export const findCountry = (slug: string): CatalogueCountry | undefined =>
  catalogue.find((country) => country.slug === slug);

/** How many different languages the catalogue covers. */
export const languageCount = new Set(
  catalogue.map((country) => country.language)
).size;

/**
 * The destination behind a catalogue country: its real card content if we
 * have written it, otherwise an empty one (no card text, no emergency
 * number) so the shop page can still be built.
 */
export const shopDestination = (slug: string): Destination | undefined => {
  const written = findDestination(slug);
  if (written) {
    return written;
  }
  const country = findCountry(slug);
  if (!country) {
    return;
  }
  return {
    slug: country.slug,
    country: country.name,
    emergencyNumber: "",
    peanutFoods: [],
    chefCard: { front: null, staffNotes: [] },
    emergencyCard: { front: null },
  };
};
